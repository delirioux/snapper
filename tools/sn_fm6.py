"""Snapper's FM6 patches -> firmware/src/sn_fm6.inc (packed 128-byte voices): Snapper's own DRONE, GLASS and PUNCH, the
ORCH HIT, and three of Tuna's
own (tools/tuna_fm6.py in Tuna, GPL-3.0, the same author), as they are.

    python3 tools/sn_fm6.py            writes it
    python3 tools/sn_fm6.py --check    fails if the file differs from what this writes

Patches made for Snapper and Tuna (no factory ROM data of any instrument), written as Felucca's own are
(tools/gen_fm6_patches.py: op() and voice(), OP1..OP6). A family loads one onto FM6 as the track's own patch
(sn_sounds.h). Tuna checked its three by ear in its audition; Snapper's is levelled by tests/sn_audition.sh.

The algorithms used (the generic 6-operator numbering):
   1  1<-2,  3<-4<-5<-6 (fb 6)             carriers 1 3
   2  1<-2 (fb 2),  3<-4<-5<-6             carriers 1 3
   5  1<-2,  3<-4,  5<-6 (fb 6)            carriers 1 3 5
  18  1<-(2, 3 fb, 4<-5<-6)                carrier 1
  32  six carriers (fb 6)                   additive
Envelope rates: higher is faster; levels 0..99. ol: output level; fc: coarse ratio (0 = 0.5); det: 7 = none.
"""
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware" / "src" / "sn_fm6.inc"
_spec = importlib.util.spec_from_file_location("gen_fm6", ROOT / "tools" / "gen_fm6_patches.py")
_g = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_g)
op, voice, pack = _g.op, _g.voice, _g.pack
OFF = op(ol=0)

# (C name, voice)
