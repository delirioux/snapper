def render():
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/sn_fm6.py: Snapper's FM6 patches (Tuna's own), packed (128 bytes); edit that, not this */"]
    for cname, v in PATCHES:
        name = "".join(chr(x) for x in v[145:155]).rstrip()
        L += [f"static const uint8_t SN_FM6_{cname}[128] = {{   /* {name} */", _g.c_rows(pack(v)), "};"]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("sn_fm6: firmware/src/sn_fm6.inc is out of date (python3 tools/sn_fm6.py)")
        print(f"sn_fm6: {len(PATCHES)} patches, up to date")
    else:
        OUT.write_text(text)
        print(f"sn_fm6: {len(PATCHES)} patches -> {OUT.relative_to(ROOT)}")
